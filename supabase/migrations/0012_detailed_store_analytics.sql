begin;
create table if not exists public.store_analytics_events(
 id bigint generated by default as identity primary key,
 store_id uuid not null references public.stores(id) on delete cascade,
 session_id uuid not null,
 visitor_id uuid not null,
 path text not null default '/',
 source text,
 occurred_at timestamptz not null default now()
);
create index if not exists store_analytics_events_store_time_idx on public.store_analytics_events(store_id,occurred_at desc);
create index if not exists store_analytics_events_session_idx on public.store_analytics_events(store_id,session_id);
alter table public.store_analytics_events enable row level security;
drop policy if exists analytics_events_public_insert on public.store_analytics_events;
create policy analytics_events_public_insert on public.store_analytics_events for insert with check(exists(select 1 from public.stores s where s.id=store_id and s.status='PUBLISHED'));
drop policy if exists analytics_events_merchant_read on public.store_analytics_events;
create policy analytics_events_merchant_read on public.store_analytics_events for select using(public.can_access_store(store_id));
notify pgrst,'reload schema';
commit;
